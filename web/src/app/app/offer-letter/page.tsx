"use client";

import { useState } from "react";
import { ModuleGate } from "@/components/ModuleGate";
import { useWorkspace } from "@/lib/workspace-context";
import { Button, Card } from "@/components/ModuleShell";

type Form = {
  candidate_name: string;
  job_title: string;
  company_name: string;
  start_date: string;
  base_salary: number;
  target_bonus_pct: number;
  lti_target_value: number;
  reporting_to: string;
  location: string;
};

const defaults: Form = {
  candidate_name: "Candidate Name",
  job_title: "Role Title",
  company_name: "Your Company",
  start_date: new Date().toISOString().slice(0, 10),
  base_salary: 180000,
  target_bonus_pct: 15,
  lti_target_value: 0,
  reporting_to: "Manager Name",
  location: "Denver, CO",
};

const inputClass =
  "mt-1 w-full rounded-xl border border-slate-200 bg-slate-50 px-3 py-2 text-sm outline-none focus:border-teal-600 focus:ring-2 focus:ring-teal-100";

function Field({ label, children }: { label: string; children: React.ReactNode }) {
  return (
    <label className="block">
      <span className="text-xs font-medium uppercase tracking-wide text-slate-500">{label}</span>
      {children}
    </label>
  );
}

export default function OfferLetterPage() {
  const { permissions } = useWorkspace();
  const [form, setForm] = useState<Form>(defaults);
  const [letter, setLetter] = useState<string | null>(null);

  function update<K extends keyof Form>(key: K, value: Form[K]) {
    setForm((prev) => ({ ...prev, [key]: value }));
    setLetter(null);
  }

  function generate() {
    const annualBonus = Math.round(form.base_salary * (form.target_bonus_pct / 100));
    const totalCash = form.base_salary + annualBonus;
    const text = `Offer Letter\n\n${form.company_name}\n${form.location}\n\nDate: ${new Date().toLocaleDateString()}\n\nDear ${form.candidate_name},\n\nWe are pleased to offer you the position of ${form.job_title} at ${form.company_name}. Your anticipated start date is ${form.start_date}. You will report to ${form.reporting_to}.\n\nCompensation\n- Base salary: $${form.base_salary.toLocaleString()} per year\n- Target bonus: ${form.target_bonus_pct}% ($${annualBonus.toLocaleString()} at target)\n- Year-1 cash at target: $${totalCash.toLocaleString()}\n${form.lti_target_value > 0 ? `- LTI / equity target value: $${form.lti_target_value.toLocaleString()}\n` : ""}\nThis offer is contingent on standard background checks and the execution of standard employment agreements. Benefits eligibility begins according to the plan documents in effect on your start date.\n\nPlease confirm your acceptance by signing and returning a copy of this letter.\n\nWe look forward to welcoming you to the team.\n\nSincerely,\n\n${form.company_name}\n\n---\nGenerated by Total Rewards Accelerator. This is a template for discussion. Review with counsel before sending.\n`;
    setLetter(text);
  }

  function download() {
    if (!letter) return;
    const blob = new Blob([letter], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `offer-letter-${form.candidate_name.replace(/\s+/g, "-").toLowerCase()}.txt`;
    a.click();
    URL.revokeObjectURL(url);
  }

  return (
    <ModuleGate module="closer" permissions={permissions}>
      <div className="space-y-6">
        <div className="max-w-2xl">
          <p className="text-xs font-semibold uppercase tracking-[0.14em] text-teal-700">
            Workspace · Offer Letter
          </p>
          <h1 className="mt-2 text-3xl font-semibold tracking-tight text-slate-900">
            Offer letter
          </h1>
          <p className="mt-2 text-slate-600">
            Generate a plain-text offer letter from the same compensation inputs used in Closer. Review and edit before sending.
          </p>
        </div>

        <div className="grid gap-6 lg:grid-cols-[1fr_1.1fr]">
          <Card>
            <h2 className="text-sm font-semibold text-slate-900">Offer details</h2>
            <div className="mt-4 space-y-3">
              <Field label="Candidate name">
                <input className={inputClass} value={form.candidate_name} onChange={(e) => update("candidate_name", e.target.value)} />
              </Field>
              <Field label="Job title">
                <input className={inputClass} value={form.job_title} onChange={(e) => update("job_title", e.target.value)} />
              </Field>
              <Field label="Company">
                <input className={inputClass} value={form.company_name} onChange={(e) => update("company_name", e.target.value)} />
              </Field>
              <Field label="Start date">
                <input type="date" className={inputClass} value={form.start_date} onChange={(e) => update("start_date", e.target.value)} />
              </Field>
              <Field label="Reporting to">
                <input className={inputClass} value={form.reporting_to} onChange={(e) => update("reporting_to", e.target.value)} />
              </Field>
              <Field label="Location">
                <input className={inputClass} value={form.location} onChange={(e) => update("location", e.target.value)} />
              </Field>
              <div className="grid grid-cols-2 gap-2">
                <Field label="Base salary ($)">
                  <input type="number" className={inputClass} value={form.base_salary} onChange={(e) => update("base_salary", Number(e.target.value))} />
                </Field>
                <Field label="Target bonus (%)">
                  <input type="number" className={inputClass} value={form.target_bonus_pct} onChange={(e) => update("target_bonus_pct", Number(e.target.value))} />
                </Field>
              </div>
              <Field label="LTI target value ($)">
                <input type="number" className={inputClass} value={form.lti_target_value} onChange={(e) => update("lti_target_value", Number(e.target.value))} />
              </Field>
            </div>
            <div className="mt-5 flex gap-2">
              <Button onClick={generate}>Generate letter</Button>
              <Button variant="secondary" disabled={!letter} onClick={download}>Download .txt</Button>
            </div>
          </Card>

          <Card>
            <h2 className="text-sm font-semibold text-slate-900">Preview</h2>
            {letter ? (
              <pre className="mt-4 whitespace-pre-wrap rounded-xl bg-slate-50 p-4 text-sm leading-relaxed text-slate-800">
                {letter}
              </pre>
            ) : (
              <p className="mt-4 text-sm text-slate-500">Generate a letter to preview it here.</p>
            )}
          </Card>
        </div>
      </div>
    </ModuleGate>
  );
}
